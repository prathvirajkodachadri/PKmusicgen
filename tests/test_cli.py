def test_cli_exact_mode():
    with tempfile.TemporaryDirectory() as tmpdir:
        midi_path = os.path.join(tmpdir, "test.mid")
        py_path = os.path.join(tmpdir, "test.py")
        create_simple_midi_file(midi_path)

        exit_code = main([midi_path, "-o", py_path, "--mode", "exact"])
        assert exit_code == 0
        assert os.path.exists(py_path)

        with open(py_path) as f:
            content = f.read()
        assert "MidiFile" in content
        assert "Generated by MIDI-to-Python" in content


