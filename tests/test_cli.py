def test_cli_stdout():
    with tempfile.TemporaryDirectory() as tmpdir:
        midi_path = os.path.join(tmpdir, "test.mid")
        create_simple_midi_file(midi_path)

        # Capture stdout by calling main with --stdout and redirecting?
        # We test via subprocess for more accurate stdout capture
        env = os.environ.copy()
        # Ensure repo root is in PYTHONPATH
        repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
        env["PYTHONPATH"] = repo_root + os.pathsep + env.get("PYTHONPATH", "")
        result = subprocess.run(
            [sys.executable, "-m", "midi2python.cli", midi_path, "--stdout"],
            capture_output=True,
            text=True,
            cwd=tmpdir,
            env=env,
        )
        # Should succeed and output code
        assert result.returncode == 0, f"stdout CLI failed: {result.stderr}"
        assert "MidiFile" in result.stdout


