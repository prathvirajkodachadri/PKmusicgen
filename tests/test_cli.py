def test_cli_invalid_output_path():
    with tempfile.TemporaryDirectory() as tmpdir:
        midi_path = os.path.join(tmpdir, "test.mid")
        create_simple_midi_file(midi_path)

        # Try to write to a directory that doesn't exist and cannot be created? Actually it can be created
        # Instead try invalid path like /proc/invalid
        # Use a path with null byte or unwritable location
        # For simplicity, use a path where parent is a file, not directory
        file_as_dir = os.path.join(tmpdir, "file")
        with open(file_as_dir, "w") as f:
            f.write("x")
        invalid_path = os.path.join(file_as_dir, "output.py")

        exit_code = main([midi_path, "-o", invalid_path])
        assert exit_code == 1


def test_cli_default_output():
    with tempfile.TemporaryDirectory() as tmpdir:
        midi_path = os.path.join(tmpdir, "song.mid")
        create_simple_midi_file(midi_path)

        # Change cwd to tmpdir for default output test
        original_cwd = os.getcwd()
        try:
            os.chdir(tmpdir)
            exit_code = main([midi_path])
            assert exit_code == 0
            # Default output should be song.py in same dir as input
            expected = os.path.join(tmpdir, "song.py")
            assert os.path.exists(expected)
        finally:
            os.chdir(original_cwd)


