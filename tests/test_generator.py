"""
Tests for code generators.
"""

import os
import tempfile

import mido
import pytest

from midi2python.generator import generate_exact_code, generate_readable_code
from midi2python.parser import parse_midi_file


def create_test_midi():
    mid = mido.MidiFile(ticks_per_beat=480, type=1)
    track = mido.MidiTrack()
    track.append(mido.MetaMessage("track_name", name="Piano", time=0))
    track.append(mido.MetaMessage("set_tempo", tempo=500000, time=0))
    track.append(mido.MetaMessage("time_signature", numerator=4, denominator=4, time=0))
    track.append(mido.Message("program_change", program=0, channel=0, time=0))
    track.append(mido.Message("note_on", note=60, velocity=64, channel=0, time=0))
    track.append(mido.Message("note_off", note=60, velocity=64, channel=0, time=480))
    track.append(mido.Message("note_on", note=62, velocity=70, channel=0, time=0))
    track.append(mido.Message("note_off", note=62, velocity=70, channel=0, time=480))
    track.append(mido.Message("control_change", control=7, value=100, channel=0, time=0))
    track.append(mido.Message("pitchwheel", pitch=200, channel=0, time=0))
    track.append(mido.MetaMessage("end_of_track", time=0))
    mid.tracks.append(track)
    return mid


def test_generate_exact_code_syntax():
    mid = create_test_midi()
    with tempfile.NamedTemporaryFile(suffix=".mid", delete=False) as f:
        mid.save(f.name)
        midi_path = f.name

    try:
        data = parse_midi_file(midi_path)
        code = generate_exact_code(data, midi_path, "test_output.py", include_comments=True)

        # Check syntax
        compile(code, "<test>", "exec")

        # Check required imports
        assert "from mido import" in code
        assert "MidiFile" in code
        assert "MidiTrack" in code

        # Check constants
        assert "TICKS_PER_BEAT" in code
        assert "OUTPUT_MIDI" in code

        # Check content preservation
        assert "note_on" in code
        assert "note_off" in code
        assert "program_change" in code

    finally:
        os.unlink(midi_path)


