def test_chord_detection_in_readable():
    # Create chord: 3 notes at same tick
    mid = mido.MidiFile(ticks_per_beat=480)
    track = mido.MidiTrack()
    track.append(mido.Message("note_on", note=60, velocity=64, channel=0, time=0))
    track.append(mido.Message("note_on", note=64, velocity=64, channel=0, time=0))
    track.append(mido.Message("note_on", note=67, velocity=64, channel=0, time=0))
    track.append(mido.Message("note_off", note=60, velocity=64, channel=0, time=480))
    track.append(mido.Message("note_off", note=64, velocity=64, channel=0, time=0))
    track.append(mido.Message("note_off", note=67, velocity=64, channel=0, time=0))
    mid.tracks.append(track)

    with tempfile.NamedTemporaryFile(suffix=".mid", delete=False) as f:
        mid.save(f.name)
        midi_path = f.name

    try:
        data = parse_midi_file(midi_path)
        code = generate_readable_code(data, midi_path, "out.py")
        # Should detect chord
        assert "CHORDS" in code or "Chord" in code
        compile(code, "<test>", "exec")
    finally:
        os.unlink(midi_path)
