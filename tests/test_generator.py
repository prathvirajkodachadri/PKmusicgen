    mid = mido.MidiFile(ticks_per_beat=480, type=1)
    for i in range(2):
        track = mido.MidiTrack()
        track.append(mido.MetaMessage("track_name", name=f"Track {i}", time=0))
        track.append(mido.Message("note_on", note=60 + i, velocity=64, channel=i, time=0))
